// TestEmptyFile verifies that all three operations handle zero-length input
// without panicking and produce a valid round-trip result.
func TestEmptyFile(t *testing.T) {
	const blockLen, strongLen = 512, 32
	sigType := librsync.BLAKE2_SIG_MAGIC
	empty := []byte{}

	sigBytes, err := adapter.SignatureBytes(empty, blockLen, strongLen, sigType)
	require.NoError(t, err)
	require.NotEmpty(t, sigBytes, "signature should at least contain its 12-byte header")

	sig, err := adapter.ParseSignature(sigBytes)
	require.NoError(t, err)

	deltaBytes, err := adapter.DeltaBytes(sig, empty)
	require.NoError(t, err)
	require.NotEmpty(t, deltaBytes, "delta should contain DELTA_MAGIC and OP_END")

	got, err := adapter.PatchBytes(empty, deltaBytes)
	require.NoError(t, err)
	require.Equal(t, empty, got)
}

