// TestBatchSignatureMatchesStreaming is the inverse of
// TestStreamingSignatureMatchesBatch: start from the streaming result and
// confirm the batch API produces the same bytes.
func TestBatchSignatureMatchesStreaming(t *testing.T) {
	tt := "003-blake2-512-32"
	file, magic, blockLen, strongLen, err := parseTestName(tt)
	require.NoError(t, err)

	input := readFile(t, testdataDir+file+".old")

	// Streaming with a chunk size that guarantees partial-block situations.
	sess, err := adapter.NewSignatureSession(blockLen, strongLen, magic)
	require.NoError(t, err)

	const chunkSize = 100 // intentionally not block-aligned
	chunks := streamFeed(t, input, chunkSize, sess.Feed)
	final, err := sess.End()
	require.NoError(t, err)
	if len(final) > 0 {
		chunks = append(chunks, final)
	}
	streamingResult := collectChunks(chunks)

	batchResult, err := adapter.SignatureBytes(input, blockLen, strongLen, magic)
	require.NoError(t, err)

	require.Equal(t, batchResult, streamingResult)
}

// TestDeltaFeedErrorStopsSession verifies the feed-after-error lifecycle
// contract: once a session's End returns an error, subsequent calls return
// the same error rather than proceeding.
func TestDeltaFeedErrorStopsSession(t *testing.T) {
	// Provide a corrupt delta to PatchSession to trigger an error on End.
	readAt := makeReadAt([]byte("base file contents"))
	sess := adapter.NewPatchSession(readAt)
	require.NoError(t, sess.Feed([]byte("not a valid delta")))

	_, err := sess.End()
	require.Error(t, err)

	// Calling End again must return an error, not panic or produce output.
	_, err2 := sess.End()
	require.Error(t, err2)
	require.Equal(t, err, err2, "repeated End must return the same error")
}

// TestStreamingDeltaEmptyChunks verifies that feeding zero-length chunks to a
// DeltaSession is a no-op and does not corrupt the output.
func TestStreamingDeltaEmptyChunks(t *testing.T) {
	tt := "001-blake2-512-32"
	file, magic, blockLen, strongLen, err := parseTestName(tt)
	require.NoError(t, err)

	oldData := readFile(t, testdataDir+file+".old")
	newData := readFile(t, testdataDir+file+".new")

	sigBytes, err := adapter.SignatureBytes(oldData, blockLen, strongLen, magic)
	require.NoError(t, err)
	sig, err := adapter.ParseSignature(sigBytes)
	require.NoError(t, err)

	want, err := adapter.DeltaBytes(sig, newData)
	require.NoError(t, err)

	sig2, err := adapter.ParseSignature(sigBytes)
	require.NoError(t, err)

	sess, err := adapter.NewDeltaSession(sig2)
	require.NoError(t, err)

	var chunks [][]byte
	out, err := sess.Feed(nil) // nil feed
	require.NoError(t, err)
	if len(out) > 0 {
		chunks = append(chunks, out)
	}
	out, err = sess.Feed([]byte{}) // empty feed
	require.NoError(t, err)
	if len(out) > 0 {
		chunks = append(chunks, out)
	}

	// Now feed the real data in one shot.
	out, err = sess.Feed(newData)
	require.NoError(t, err)
	if len(out) > 0 {
		chunks = append(chunks, out)
	}

	final, err := sess.End()
	require.NoError(t, err)
	if len(final) > 0 {
		chunks = append(chunks, final)
	}

	require.Equal(t, want, collectChunks(chunks))
}

// TestCallbackSeekBehavior verifies the callbackReadSeeker correctly handles
// non-sequential seeks, which Patch uses when processing COPY operations out
// of order.
func TestCallbackSeekBehavior(t *testing.T) {
	// Build a base file with a recognizable pattern at known offsets.
	base := bytes.Repeat([]byte("ABCDEFGHIJ"), 100) // 1000 bytes

	// Create a delta that COPY's a non-first region and then the start.
	// We verify this by doing a full round-trip with a file designed to
	// have out-of-order COPY operations.
	const blockLen uint32 = 10
	const strongLen uint32 = 32

	sigBytes, err := adapter.SignatureBytes(base, blockLen, strongLen, librsync.BLAKE2_SIG_MAGIC)
	require.NoError(t, err)
	sig, err := adapter.ParseSignature(sigBytes)
	require.NoError(t, err)

	// New file is the base with its two halves swapped.
	half := len(base) / 2
	swapped := append(append([]byte{}, base[half:]...), base[:half]...)

	deltaBytes, err := adapter.DeltaBytes(sig, swapped)
	require.NoError(t, err)

	got, err := adapter.PatchWithCallback(makeReadAt(base), deltaBytes)
	require.NoError(t, err)
	require.Equal(t, swapped, got)
}
