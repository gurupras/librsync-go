func parseTestName(name string) (file string, magic librsync.MagicNumber, blockLen, strongLen uint32, err error) {
	segs := strings.Split(name, "-")
	if len(segs) != 4 {
		return "", 0, 0, 0, fmt.Errorf("invalid format %q", name)
	}
	file = segs[0]
	switch segs[1] {
	case "blake2":
		magic = librsync.BLAKE2_SIG_MAGIC
	case "md4":
		magic = librsync.MD4_SIG_MAGIC
	default:
		return "", 0, 0, 0, fmt.Errorf("unknown hash %q", segs[1])
	}
	bl, err := strconv.ParseUint(segs[2], 10, 32)
	if err != nil {
		return "", 0, 0, 0, fmt.Errorf("bad blockLen %q", segs[2])
	}
	sl, err := strconv.ParseUint(segs[3], 10, 32)
	if err != nil {
		return "", 0, 0, 0, fmt.Errorf("bad strongLen %q", segs[3])
	}
	return file, magic, uint32(bl), uint32(sl), nil
}

func readFile(t *testing.T, path string) []byte {
	t.Helper()
	data, err := os.ReadFile(path)
	require.NoError(t, err, "reading %s", path)
	return data
}

// collectChunks concatenates streaming output chunks into a single slice,
// ignoring nil chunks (no-output feeds).
func collectChunks(chunks [][]byte) []byte {
	var out []byte
	for _, c := range chunks {
		out = append(out, c...)
	}
	return out
}

// streamFeed feeds data into a function in chunkSize-byte pieces, collecting
// all non-nil output chunks.
func streamFeed(t *testing.T, data []byte, chunkSize int, feed func([]byte) ([]byte, error)) [][]byte {
	t.Helper()
	var chunks [][]byte
	for i := 0; i < len(data); i += chunkSize {
		end := i + chunkSize
		if end > len(data) {
			end = len(data)
		}
		out, err := feed(data[i:end])
		require.NoError(t, err)
		if len(out) > 0 {
			chunks = append(chunks, out)
		}
	}
	return chunks
}

