func makeReadAt(base []byte) adapter.ReadAtFunc {
	return func(offset int64, buf []byte) (int, error) {
		if int(offset) >= len(base) {
			return 0, io.EOF
		}
		n := copy(buf, base[offset:])
		return n, nil
	}
}

