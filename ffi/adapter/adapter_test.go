var streamingChunkSizes = []int{64, 512, 4096, 65536}

// TestStreamingSignatureMatchesBatch confirms that streaming signature output,
// concatenated, is byte-for-byte identical to batch output regardless of chunk
// size. This validates the partial-block accumulation logic in SignatureSession.
func TestStreamingSignatureMatchesBatch(t *testing.T) {
	for _, tt := range allTestCases {
		file, magic, blockLen, strongLen, err := parseTestName(tt)
		require.NoError(t, err)

		input := readFile(t, testdataDir+file+".old")
		want, err := adapter.SignatureBytes(input, blockLen, strongLen, magic)
		require.NoError(t, err)

		for _, chunkSize := range streamingChunkSizes {
			t.Run(fmt.Sprintf("%s/chunk%d", tt, chunkSize), func(t *testing.T) {
				sess, err := adapter.NewSignatureSession(blockLen, strongLen, magic)
				require.NoError(t, err)

				chunks := streamFeed(t, input, chunkSize, sess.Feed)

				final, err := sess.End()
				require.NoError(t, err)
				if len(final) > 0 {
					chunks = append(chunks, final)
				}

				require.Equal(t, want, collectChunks(chunks))
			})
		}
	}
}

