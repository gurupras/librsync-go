// ── Full streaming round-trip ─────────────────────────────────────────────────

// TestFullStreamingRoundTrip exercises all three streaming sessions in sequence:
// signature → delta → patch, feeding data in chunks at each stage.
func TestFullStreamingRoundTrip(t *testing.T) {
	for _, tt := range allTestCases {
		t.Run(tt, func(t *testing.T) {
			file, magic, blockLen, strongLen, err := parseTestName(tt)
			require.NoError(t, err)

			oldData := readFile(t, testdataDir+file+".old")
			newData := readFile(t, testdataDir+file+".new")

			const chunkSize = 4096

			// 1. Streaming signature over old file.
			sigSess, err := adapter.NewSignatureSession(blockLen, strongLen, magic)
			require.NoError(t, err)
			sigChunks := streamFeed(t, oldData, chunkSize, sigSess.Feed)
			final, err := sigSess.End()
			require.NoError(t, err)
			if len(final) > 0 {
				sigChunks = append(sigChunks, final)
			}
			sigBytes := collectChunks(sigChunks)

			sig, err := adapter.ParseSignature(sigBytes)
			require.NoError(t, err)

			// 2. Streaming delta over new file.
			deltaSess, err := adapter.NewDeltaSession(sig)
			require.NoError(t, err)
			deltaChunks := streamFeed(t, newData, chunkSize, deltaSess.Feed)
			final, err = deltaSess.End()
			require.NoError(t, err)
			if len(final) > 0 {
				deltaChunks = append(deltaChunks, final)
			}
			deltaBytes := collectChunks(deltaChunks)

			// 3. Streaming patch using callback for old file.
			patchSess := adapter.NewPatchSession(makeReadAt(oldData))
			for i := 0; i < len(deltaBytes); i += chunkSize {
				end := i + chunkSize
				if end > len(deltaBytes) {
					end = len(deltaBytes)
				}
				require.NoError(t, patchSess.Feed(deltaBytes[i:end]))
			}
			got, err := patchSess.End()
			require.NoError(t, err)

			require.Equal(t, newData, got)
		})
	}
}

